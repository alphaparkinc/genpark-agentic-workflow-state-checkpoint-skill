import json, sys
from client import AgenticWorkflowStateCheckpointClient

def handle_mcp_request(payload):
    method = payload.get("method")
    req_id = payload.get("id", 1)
    if method == "initialize":
        return {"jsonrpc": "2.0", "id": req_id, "result": {"protocolVersion": "2024-11-05", "serverInfo": {"name": "workflow-state-checkpoint", "version": "1.0.0"}}}
    elif method == "tools/list":
        return {"jsonrpc": "2.0", "id": req_id, "result": {"tools": [{"name": "commit_state_checkpoint", "description": "Commit state checkpoint with SHA-256 hash and rollback transaction support."}]}}
    elif method == "tools/call":
        client = AgenticWorkflowStateCheckpointClient()
        res = client.commit_state_checkpoint()
        return {"jsonrpc": "2.0", "id": req_id, "result": {"content": [{"type": "text", "text": json.dumps(res, indent=2)}]}}
    return {"jsonrpc": "2.0", "id": req_id, "result": {"status": "ACTIVE"}}

if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--test":
        print(json.dumps(handle_mcp_request({"method": "tools/list"})))
    else:
        client = AgenticWorkflowStateCheckpointClient()
        print(json.dumps(client.commit_state_checkpoint(), indent=2))
